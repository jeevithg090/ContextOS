export function facets(items: ContextItemSummary[], simulated = 0): ContextFacets {
  const count = (pick: (i: ContextItemSummary) => string) => {
    const map = new Map<string, number>();
    for (const i of items) map.set(pick(i), (map.get(pick(i)) ?? 0) + 1);
    return [...map].map(([value, n]) => ({ value, count: n }));
  };
  return {
    total: items.length,
    by_trust_level: count((i) => i.trust_level),
    by_sensitivity: count((i) => i.sensitivity),
    by_source_type: count((i) => i.source.source_type),
    with_detections: items.filter((i) => i.detection.hit_count > 0).length,
    with_secrets: items.filter((i) => i.contains_secrets).length,
    simulated_total: simulated,
  };
}

