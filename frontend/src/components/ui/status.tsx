/** Domain status badges. Always use these for trust / severity / decision / enforcement so the
 * same value looks identical on every screen. */
import { Badge } from "./primitives";
import {
  DECISION_META,
  ENFORCEMENT_META,
  SEVERITY_META,
  TRUST_META,
  decisionTone,
  humanize,
  severityTone,
  trustTone,
  type Decision,
  type EnforcementMode,
  type Severity,
  type Tone,
  type TrustLevel,
} from "@/lib/domain";

export function TrustBadge({ level, className }: { level?: string | null; className?: string }) {
  const meta = level ? TRUST_META[level as TrustLevel] : undefined;
  return (
    <Badge tone={trustTone(level)} dot className={className} title={meta?.description}>
      {meta?.label ?? humanize(level)}
    </Badge>
  );
}

export function SeverityBadge({ severity, className }: { severity?: string | null; className?: string }) {
  const meta = severity ? SEVERITY_META[severity as Severity] : undefined;
  return (
    <Badge tone={severityTone(severity)} className={className}>
      {meta?.label ?? humanize(severity)}
    </Badge>
  );
}

export function DecisionBadge({ decision, className }: { decision?: string | null; className?: string }) {
  const meta = decision ? DECISION_META[decision as Decision] : undefined;
  return (
    <Badge tone={decisionTone(decision)} className={className} title={meta?.description}>
      {meta?.label ?? humanize(decision)}
    </Badge>
  );
}

export function EnforcementBadge({ mode, className }: { mode?: string | null; className?: string }) {
  const meta = mode ? ENFORCEMENT_META[mode as EnforcementMode] : undefined;
  return (
    <Badge tone={meta?.tone ?? "neutral"} className={className} title={meta?.description}>
      {meta?.label ?? humanize(mode)}
    </Badge>
  );
}

const STATUS_TONES: Record<string, Tone> = {
  open: "high",
  acknowledged: "medium",
  investigating: "medium",
  contained: "low",
  resolved: "ok",
  false_positive: "neutral",
  pending: "approval",
  approved: "allow",
  rejected: "deny",
  expired: "neutral",
  cancelled: "neutral",
  active: "ok",
  ended: "neutral",
  inactive: "neutral",
  quarantined: "deny",
  connected: "ok",
  stale: "warn",
  never_seen: "neutral",
  error: "danger",
  running: "accent",
  completed: "ok",
  failed: "danger",
  passed: "ok",
  unverified: "neutral",
};

export function StatusBadge({ status, className }: { status?: string | null; className?: string }) {
  return (
    <Badge tone={(status && STATUS_TONES[status]) || "neutral"} dot className={className}>
      {humanize(status)}
    </Badge>
  );
}

/** Explicit label for simulated data so it is never confused with real activity. */
export function SimulationBadge() {
  return (
    <Badge tone="accent" title="Generated by the Simulation Lab with synthetic data">
      Simulation
    </Badge>
  );
}
